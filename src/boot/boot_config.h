#ifndef BOOT_CONFIG_H
#define BOOT_CONFIG_H

/* ====================================================================
 *  Настройки загрузочного экрана EquinoxOS
 *  --------------------------------------------------------------------
 *  Поменяй значения ниже и пересобери ядро (make), чтобы изменить вид
 *  загрузки. Это единственное место, где настраивается boot-экран.
 * ==================================================================== */

/* Режим загрузочного экрана:
 *   0 = крутящийся Nyan Cat на чёрном фоне   (по умолчанию, как сейчас)
 *   1 = статичный Nyan Cat на сером экране    ("серый экран нянкета")
 *
 * Поставь 1 — и загрузка вернётся к серому экрану с неподвижным Nyan'ом.
 */
#define BOOT_SCREEN_MODE 1

/* Цвет "серого экрана" (0xRRGGBB). Используется только при BOOT_SCREEN_MODE==1. */
#define BOOT_GRAY_COLOR 0x202225

/* Прогресс-бар с процентами и примерным оставшимся временем:
 *   1 = показывать, 0 = скрыть. */
#define BOOT_PROGRESS_BAR 1

/* Примерное полное время загрузки в миллисекундах — основа для расчёта
 * процентов и оставшегося времени. Бар линейно идёт 0..97% за это время,
 * а последние 97..99% ползут медленно (по +1% раз в BOOT_TAIL_STEP_MS).
 *
 * САМОПОДСТРОЙКА: это значение используется только на ПЕРВОМ запуске (или
 * если файл /boottime на EXT2-диске стёрт, напр. после `make all`). По
 * завершении загрузки ядро сохраняет РЕАЛЬНОЕ измеренное время в /boottime,
 * и при следующих запусках бар считает уже по нему — время становится
 * точнее. Стартовое значение специально с запасом (учитывает интерактивный
 * USB-тест мыши ~18 c), чтобы на первом запуске бар не упирался в 99%. */
#define BOOT_ETA_MS 48000

/* Доползание хвоста 97%->99% после BOOT_ETA_MS: +1% за столько миллисекунд.
 * Чем больше — тем медленнее и дольше «дышит» хвост (не выглядит застрявшим). */
#define BOOT_TAIL_STEP_MS 4000

/* --- ПОЛОЖЕНИЕ И РАЗМЕР ПРОГРЕСС-БАРА (в процентах от размеров экрана) ---
 * Подстрой, если бар перекрывается гифкой Nyan Cat (она в левом-центре).
 *   BOOT_BAR_CX_PCT — центр бара по горизонтали (0=левый край, 100=правый).
 *   BOOT_BAR_Y_PCT  — верх бара по вертикали     (0=верх,       100=низ).
 *   BOOT_BAR_W_PCT  — ширина бара.
 * По умолчанию бар поднят выше и сдвинут вправо, чтобы не лез под кота. */
#define BOOT_BAR_CX_PCT 62
#define BOOT_BAR_Y_PCT  24
#define BOOT_BAR_W_PCT  34

#endif /* BOOT_CONFIG_H */
