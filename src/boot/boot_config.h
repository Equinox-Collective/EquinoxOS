#ifndef BOOT_CONFIG_H
#define BOOT_CONFIG_H

/* ====================================================================
 *  БЫСТРАЯ ЗАГРУЗКА (FAST_BOOT)
 *  --------------------------------------------------------------------
 *  1 = релизный режим: пропускаем искусственные паузы, тяжёлую boot-
 *      диагностику и стресс-тесты ФС/PMM, которые гонялись на КАЖДОМ
 *      запуске. Драйверы, не нужные для первого кадра GUI (PCI/USB/звук/
 *      сеть), инициализируются в фоне ПОСЛЕ запуска рабочего стола.
 *  0 = отладочный режим: полный диагностический лог и все тесты.
 *
 *  Можно переопределить из Makefile через -DFAST_BOOT=0.
 * ==================================================================== */
#ifndef FAST_BOOT
#define FAST_BOOT 1
#endif

/* Откладывать инициализацию «тяжёлого» железа (PCI/USB/звук/сеть, мышь)
 * в фоновый поток ПОСЛЕ старта sysgui — рабочий стол появляется раньше.
 * Если на твоём железе мышь/сеть поднимаются криво — поставь 0. */
#ifndef DEFER_HW_INIT
#define DEFER_HW_INIT FAST_BOOT
#endif

/* ====================================================================
 *  Настройки загрузочного экрана EquinoxOS
 *  --------------------------------------------------------------------
 *  Поменяй значения ниже и пересобери ядро (make), чтобы изменить вид
 *  загрузки. Это единственное место, где настраивается boot-экран.
 * ==================================================================== */

/* Режим загрузочного экрана:
 *   0 = крутящийся Nyan Cat на чёрном фоне   (по умолчанию, как сейчас)
 *   1 = статичный Nyan Cat на сером экране    ("серый экран нянкета")
 *
 * Поставь 1 — и загрузка вернётся к серому экрану с неподвижным Nyan'ом.
 */
#define BOOT_SCREEN_MODE 0

/* Цвет "серого экрана" (0xRRGGBB). Используется только при BOOT_SCREEN_MODE==1. */
#define BOOT_GRAY_COLOR 0x202225

/* Прогресс-бар с процентами и примерным оставшимся временем:
 *   1 = показывать, 0 = скрыть. */
#define BOOT_PROGRESS_BAR 1

/* Примерное полное время загрузки в миллисекундах — основа для расчёта
 * процентов и оставшегося времени. Бар линейно идёт 0..97% за это время,
 * а последние 97..99% ползут медленно (по +1% раз в BOOT_TAIL_STEP_MS).
 *
 * САМОПОДСТРОЙКА: это значение используется только на ПЕРВОМ запуске (или
 * если файл /boottime на EXT2-диске стёрт, напр. после `make all`). По
 * завершении загрузки ядро сохраняет РЕАЛЬНОЕ измеренное время в /boottime,
 * и при следующих запусках бар считает уже по нему — время становится
 * точнее. Стартовое значение специально с запасом (учитывает интерактивный
 * USB-тест мыши ~18 c), чтобы на первом запуске бар не упирался в 99%. */
#if FAST_BOOT
/* В быстром режиме реальная загрузка ~3-5 c, поэтому стартовая оценка ниже,
 * чтобы прогресс-бар не полз. После первого старта уточняется по /boottime. */
#define BOOT_ETA_MS 4000
#else
#define BOOT_ETA_MS 48000
#endif

/* Доползание хвоста 97%->99% после BOOT_ETA_MS: +1% за столько миллисекунд.
 * Чем больше — тем медленнее и дольше «дышит» хвост (не выглядит застрявшим). */
#define BOOT_TAIL_STEP_MS 4000

/* --- ПОЛОЖЕНИЕ И РАЗМЕР ПРОГРЕСС-БАРА (в процентах от размеров экрана) ---
 * Подстрой, если бар перекрывается гифкой Nyan Cat (она в левом-центре).
 *   BOOT_BAR_CX_PCT — центр бара по горизонтали (0=левый край, 100=правый).
 *   BOOT_BAR_Y_PCT  — верх бара по вертикали     (0=верх,       100=низ).
 *   BOOT_BAR_W_PCT  — ширина бара.
 * Новая раскладка: логотип/надпись — сверху, прогресс-бар/спиннер — по
 * центру, Nyan Cat (если включён) — внизу. */
#define BOOT_BAR_CX_PCT 50
#define BOOT_BAR_Y_PCT  50
#define BOOT_BAR_W_PCT  36

/* ====================================================================
 *  ПЕРЕКЛЮЧАТЕЛИ ЭЛЕМЕНТОВ ЗАГРУЗОЧНОГО ЭКРАНА (режим 0)
 *  --------------------------------------------------------------------
 *  Логотип EquinoxOS + надпись показываются всегда. Ниже включаются/
 *  выключаются остальные элементы (1 = показывать, 0 = скрыть):
 *    BOOT_SHOW_NYAN     — анимированный Nyan Cat внизу экрана.
 *    BOOT_SHOW_PROGRESS — прогресс-бар по центру.
 *    BOOT_SHOW_SPINNER  — круговой спиннер в стиле Windows 11.
 *  По умолчанию: только спиннер (как на Win11), без кота и без бара. */
#define BOOT_SHOW_NYAN     0
#define BOOT_SHOW_PROGRESS 0
#define BOOT_SHOW_SPINNER  1

/* Положение центра спиннера (в % от размеров экрана) и его размер.
 *   BOOT_SPINNER_Y_PCT — центр по вертикали (X всегда по центру экрана).
 *   BOOT_SPINNER_ROT_MS — период полного оборота (мс), меньше = быстрее. */
#define BOOT_SPINNER_Y_PCT  60
#define BOOT_SPINNER_ROT_MS 1200

/* ====================================================================
 *  ЗВУК ПРИ СТАРТЕ СИСТЕМЫ
 *  --------------------------------------------------------------------
 *  Загрузочный экран рисует ЯДРО, а звук запуска проигрывает рабочий
 *  стол (sysgui) — это отдельный бинарник, поэтому переключатель музыки
 *  живёт НЕ здесь, а в графической подсистеме:
 *      app/sysgui (enGUI) -> scripts/bootvid.lua, переменная
 *      BOOT_SOUND_ENABLED = true/false  (вверху файла).
 *  Поставь там false и пересобери (make all), чтобы старт был без звука.
 * ==================================================================== */

#endif /* BOOT_CONFIG_H */
