[bits 64]

; Этап 4: трамплин возврата из обработчика сигнала.
;
; Адрес этой метки регистрируется ядром как sa_restorer. Когда
; пользовательский обработчик сигнала делает `ret`, управление приходит сюда
; (адрес был положен ядром как адрес возврата на стек обработчика).
;
; КРИТИЧЕСКИ ВАЖНО: на входе сюда RSP указывает РОВНО на sigframe_t, который
; ядро ожидает прочитать по regs->rsp в SYS_SIGRETURN. Поэтому здесь НЕЛЬЗЯ
; ничего пушить/менять RSP до `int 0x80` — иначе ядро прочтёт мусор. Это
; единственная причина, по которой трамплин написан на ассемблере, а не на C
; (пролог C-функции сдвинул бы RSP).

section .text
global __equos_sigreturn_trampoline
__equos_sigreturn_trampoline:
    mov rax, 104        ; SYS_SIGRETURN
    int 0x80
    ; не возвращается: ядро восстановит прерванный контекст
.hang:
    jmp .hang
